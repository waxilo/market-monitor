/**
 * 窗口拖拽的「位移死区」判据 —— 纯函数、零依赖，便于用 Node 直接跑边界单测
 * （见 `.workbuddy/tmp/verify-drag-threshold.mts`）。
 *
 * 为什么是**位移**而不是**时长**：早先悬浮窗靠「按住 200ms 才拖」把「点行选中」和
 * 「搬窗口」分开。那条路是错的 ——
 *   1. 定时器与指针动没动**完全无关**，所以想拖必须先原地干等，手感发死；
 *   2. 按下就立刻移动时，这 200ms 内窗口一动不动，等定时器到点才从**当时的**指针位置
 *      开始跟手，前面那段位移被整段丢掉 ⇒ 视觉上「先愣一下再跳着跟」；
 *   3. 反向还有个 bug：按住后移动但没满 200ms 就抬手，因为还没进拖拽态，
 *      系统补发的 click 不被吞 ⇒ **快速拖一下会被当成点击**（窗口直接切走）。
 * 换成位移死区后：想拖就直接拖（零等待），想点就不动（纯点击）。
 */

/**
 * 超过这么多像素才认为「用户是要搬窗口」。
 *
 * 取 4 不是拍脑袋：Windows 自己的拖拽死区就是 `SM_CXDRAG` / `SM_CYDRAG` 的系统默认值
 * 4px，原生标题栏拖动同样要先过这段死区。**只有与原生一致才不会别扭** ——
 * 比原生小，手抖的点击会被吃成拖动；比原生大，想拖却拖不动。
 */
export const DRAG_THRESHOLD_PX = 4;

/**
 * 位移是否已越过死区。用欧氏距离而不是「只看 X 或只看 Y」：
 * 斜着拖（尤其悬浮窗很窄，横向很容易凑够而纵向不够）也必须能起来。
 *
 * 边界是**严格大于**：位移正好 = 阈值时**不**触发（与「死区」的语义一致）。
 */
export function pastDragThreshold(
  x0: number,
  y0: number,
  x1: number,
  y1: number,
  threshold = DRAG_THRESHOLD_PX,
): boolean {
  const dx = x1 - x0;
  const dy = y1 - y0;
  return dx * dx + dy * dy > threshold * threshold;
}
